export function canTransitionPrisoner(currentState, nextState) {
  if (!currentState) return true;
  if (currentState === nextState) return true;
  const permitted = PRISONER_TRANSITIONS[currentState];
  return permitted ? permitted.includes(nextState) : true;
}

export function canTransitionOfficer(currentState, nextState) {
  if (!currentState) return true;
  if (currentState === nextState) return true;
  const permitted = OFFICER_TRANSITIONS[currentState];
  return permitted ? permitted.includes(nextState) : true;
}
